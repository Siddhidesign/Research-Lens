/**
 * Builds docs/index.html as a single self-contained file.
 *
 * Sources, each the single source of truth for its part:
 *   data/sessions.json      the research repository
 *   docs/tools.mjs          the five tool functions, ported from src/index.ts
 *   docs/page.mjs           the demo UI
 *   docs/index.template.html  markup and styles
 *
 * Everything is inlined so the page works from file://, from a static server,
 * and from GitHub Pages with no build step on the host and no dependencies.
 *
 * Run: node docs/build.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const read = (...p) => readFileSync(join(here, ...p), "utf-8");

const json = read("..", "data", "sessions.json");
JSON.parse(json); // fail loudly if the source JSON is malformed

// Keep sessions.js on disk too, so verify_parity.mjs imports the same data.
writeFileSync(
  join(here, "sessions.js"),
  "// GENERATED from data/sessions.json by docs/build.mjs. Do not edit by hand.\n" +
    "export const REPO = " + json.trim() + ";\n"
);

const stripModuleSyntax = (s) =>
  s
    .replace(/^export \{[^}]*\};?\s*$/gm, "")
    .replace(/^export (const|function|class) /gm, "$1 ")
    .replace(/^import .*?;\s*$/gm, "");

const inlined = [
  "// GENERATED by docs/build.mjs from data/sessions.json, docs/tools.mjs and docs/page.mjs.",
  "// Edit those files, not this block.",
  "const REPO = " + json.trim() + ";",
  stripModuleSyntax(read("tools.mjs")),
  stripModuleSyntax(read("page.mjs")),
].join("\n\n");

const out = read("index.template.html").replace(
  "<!--INLINE_SCRIPT-->",
  "<script>\n" + inlined + "\n</script>"
);

writeFileSync(join(here, "index.html"), out);
console.log(`wrote docs/index.html (${(out.length / 1024).toFixed(1)} KB, self-contained)`);
